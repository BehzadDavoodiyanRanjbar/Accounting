describe('شباهت مبلغ حروفی', () => {
  it('کلمه‌های مبلغ درست تولید می‌شود', () => {
    expect(numberToWordTokens(336_178_851).join(' ')).toBe('سیصد سی شش میلیون یکصد هفتاد هشت هزار هشتصد پنجاه یک');
    expect(numberToWordTokens(1_000)).toEqual(['هزار']);
  });
  it('متن حروفی با غلط OCR هنوز شبیه است، مبلغ دیگر نه', () => {
    const noisy = 'سیصد وسی وشش میلیون و بکصد و هفتاد و هشت هزار و هشتصد و ... یک';
    expect(wordsMatchScore(336_178_851, noisy) >= 0.8).toBe(true);
    expect(wordsMatchScore(21_600_000, noisy) < 0.8).toBe(true);
  });
  it('حروف ناقص/خراب اطمینان را به ۰٫۵ نمی‌رساند، فقط ۰٫۷', () => {
    const t = TAMIN.replace(/مبلغ حق بیمه پرداخت شده به حروف:.*\nریال/, 'مبلغ حق بیمه پرداخت شده به حروف: سید وس وخش\nریال');
    expect(insuranceFromText(t).doc.conf).toBe(0.7);
  });
  it('دوره با سرستون‌های در خط‌های جدا', () => {
    const t = TAMIN.replace('سال: 1405 ماه: مهر', 'سال: 1405\nماه:\nمهر');
    expect(insuranceFromText(t).doc.periodMonth).toBe('1405/07');
  });
});

describe('خروجی واقعی OCR فارسی', () => {
  for (const [name, txt] of [['PSM4', REAL_PSM4], ['PSM6', REAL_PSM6]] as const) {
    it(`${name}: مبلغ، پیگیری، تاریخ، دوره`, () => {
      const { doc } = insuranceFromText(txt);
      expect(doc.amount).toBe(336_178_851);
      expect(doc.trackingNo).toBe('949487');
      expect(doc.date).toBe('1405/08/15');
      expect(doc.periodMonth).toBe('1405/07');
      expect(doc.conf < 0.85).toBe(true);
    });
  }
  it('PSM4: مبلغ حروفی با غلط‌های OCR (وسی، بکصد) خوانده می‌شود', () => {
    expect(amountsInWords(REAL_PSM4.replace(/\u200f|\u200e/g, ''))).toContain(336_178_851);
  });
});
